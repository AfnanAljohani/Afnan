-- EWA AI Club · «المكتبة الرقمية»
-- Sources (RSS/Atom feeds) are fetched daily by /api/cron/library.
-- Items are deduplicated by a hash of the canonical URL.
-- Every run is logged in library_runs; the public page shows the last
-- successful run time from that log.

create table public.library_categories (
  slug       text primary key check (slug ~ '^[a-z0-9-]{2,40}$'),
  name_ar    text not null,
  name_en    text not null,
  keywords   text[] not null default '{}',   -- lowercase match terms used by the fetcher
  sort_order integer not null default 0,
  status     public.publish_status not null default 'published',
  updated_at timestamptz not null default now(),
  updated_by uuid
);
create trigger library_categories_touch before update on public.library_categories
  for each row execute function private.touch_updated();

create table public.library_sources (
  id              uuid primary key default gen_random_uuid(),
  name            text not null check (char_length(name) between 1 and 120),
  feed_url        text not null unique check (feed_url ~ '^https://'),
  site_url        text not null check (site_url ~ '^https://'),
  content_type    text not null check (content_type in ('news', 'article', 'research', 'learning')),
  language        text not null check (language in ('ar', 'en')),
  default_category text references public.library_categories (slug) on update cascade on delete set null,
  is_saudi        boolean not null default false,  -- every item from this source counts as «السعودية»
  filter_keywords text[] not null default '{}',    -- keep only items whose title/summary match one of these (for general news feeds)
  use_images      boolean not null default true,   -- show the image the feed itself provides (enclosure / media:content)
  enabled         boolean not null default true,
  max_items       integer not null default 15 check (max_items between 1 and 50),
  last_ok_at      timestamptz,
  last_error      text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  updated_by      uuid
);
create trigger library_sources_touch before update on public.library_sources
  for each row execute function private.touch_updated();

create table public.library_items (
  id            uuid primary key default gen_random_uuid(),
  source_id     uuid references public.library_sources (id) on delete set null,
  source_name   text not null,                 -- kept even if the source is removed later
  url           text not null check (url ~ '^https://'),
  url_hash      text not null unique,          -- sha256 of the normalized URL → no duplicates
  title         text not null check (char_length(title) between 1 and 400),
  excerpt       text check (char_length(excerpt) <= 600),  -- plain-text snippet from the feed (original language)
  summary_ar    text check (char_length(summary_ar) <= 700),
  summary_is_ai boolean not null default false,  -- true when summary_ar was generated by the model
  language      text not null check (language in ('ar', 'en')),
  category      text references public.library_categories (slug) on update cascade on delete set null,
  content_type  text not null check (content_type in ('news', 'article', 'research', 'learning')),
  is_saudi      boolean not null default false,
  image_url     text check (image_url is null or image_url ~ '^https://'),
  published_at  timestamptz,                   -- date given by the source (null if the feed omits it)
  fetched_at    timestamptz not null default now(),   -- first time we saw it
  refreshed_at  timestamptz not null default now(),   -- last time the fetcher updated it
  status        public.publish_status not null default 'published',
  search        tsvector generated always as (
                  to_tsvector('simple',
                    coalesce(title, '') || ' ' || coalesce(summary_ar, '') || ' ' ||
                    coalesce(excerpt, '') || ' ' || coalesce(source_name, ''))
                ) stored,
  updated_at    timestamptz not null default now(),
  updated_by    uuid
);
create index library_items_feed_idx   on public.library_items (status, published_at desc nulls last, fetched_at desc);
create index library_items_cat_idx    on public.library_items (status, category, published_at desc nulls last);
create index library_items_saudi_idx  on public.library_items (status, published_at desc nulls last) where is_saudi;
create index library_items_search_idx on public.library_items using gin (search);
create index library_items_source_idx on public.library_items (source_id);
create trigger library_items_touch before update on public.library_items
  for each row execute function private.touch_updated();

create table public.library_runs (
  id            bigint generated always as identity primary key,
  trigger       text not null check (trigger in ('schedule', 'manual')),
  started_at    timestamptz not null default now(),
  finished_at   timestamptz,
  ok            boolean,                 -- null while running
  sources_total integer not null default 0,
  sources_ok    integer not null default 0,
  items_new     integer not null default 0,
  items_updated integer not null default 0,
  errors        jsonb not null default '[]'::jsonb
);
create index library_runs_recent_idx on public.library_runs (started_at desc);
create index library_runs_ok_idx on public.library_runs (finished_at desc) where ok;

-- Grants -------------------------------------------------------------------
grant select on public.library_categories, public.library_items to anon, authenticated;
grant select (id, name, site_url, content_type, language, is_saudi, enabled) on public.library_sources to anon;
grant select on public.library_sources to authenticated;
-- visitors only ever see when the last successful run finished
grant select (id, finished_at, ok, items_new) on public.library_runs to anon;
grant select on public.library_runs to authenticated;
grant insert, update, delete on public.library_categories, public.library_sources, public.library_items to authenticated;
grant all on public.library_categories, public.library_sources, public.library_items, public.library_runs to service_role;
grant usage, select on sequence public.library_runs_id_seq to service_role;

alter table public.library_categories enable row level security;
alter table public.library_sources    enable row level security;
alter table public.library_items      enable row level security;
alter table public.library_runs       enable row level security;

-- Policies -----------------------------------------------------------------
create policy "lib cats: read published or admin" on public.library_categories
  for select to anon, authenticated using (status = 'published' or (select private.is_admin()));
create policy "lib cats: admin write" on public.library_categories
  for all to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));

create policy "lib sources: read enabled or admin" on public.library_sources
  for select to anon, authenticated using (enabled or (select private.is_admin()));
create policy "lib sources: admin write" on public.library_sources
  for all to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));

create policy "lib items: read published or admin" on public.library_items
  for select to anon, authenticated using (status = 'published' or (select private.is_admin()));
create policy "lib items: admin write" on public.library_items
  for all to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));

create policy "lib runs: public sees successful runs" on public.library_runs
  for select to anon using (ok is true);
create policy "lib runs: admin read" on public.library_runs
  for select to authenticated using (ok is true or (select private.is_admin()));
-- runs are written only by the server (service_role bypasses RLS)

