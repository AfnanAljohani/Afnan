"""Build the site's content files from one source of truth.

bnan/data/content.json  ->  bnan/js/content-data.js   (offline fallback for the frontend)
                        ->  backend/supabase/seed.sql (rows for the Supabase database)

Run after editing content.json:  python3 tools/build_content.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'bnan' / 'data' / 'content.json'
JS_OUT = ROOT / 'bnan' / 'js' / 'content-data.js'
SQL_OUT = ROOT / 'backend' / 'supabase' / 'seed.sql'


def q(value):
    return "'" + str(value).replace("'", "''") + "'"


def arr(values):
    return 'array[' + ', '.join(q(v) for v in values) + ']::text[]' if values else "'{}'::text[]"


def upsert(table, cols, rows):
    head = f'insert into public.{table} ({", ".join(cols)}) values\n'
    body = ',\n'.join('  (' + ', '.join(r) + ')' for r in rows)
    updates = ', '.join(f'{c} = excluded.{c}' for c in cols if c != 'slug')
    return f'{head}{body}\non conflict (slug) do update set {updates};\n'


def main():
    data = json.loads(SRC.read_text(encoding='utf-8'))

    JS_OUT.write_text(
        '// Generated by tools/build_content.py from data/content.json. Do not edit by hand.\n'
        'window.BNAN_CONTENT = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n',
        encoding='utf-8')

    sql = ['-- Generated by tools/build_content.py from bnan/data/content.json. Do not edit by hand.\n']
    sql.append(upsert('projects',
        ['slug', 'status', 'progress', 'icon', 'year_label', 'tags', 'title_ar', 'title_en', 'summary_ar', 'summary_en', 'sort_order'],
        [[q(p['slug']), q(p['status']), str(p['progress']), q(p['icon']), q(p['year']), arr(p['tags']),
          q(p['title']['ar']), q(p['title']['en']), q(p['summary']['ar']), q(p['summary']['en']), str(p['sort'])]
         for p in data['projects']]))
    sql.append(upsert('decks',
        ['slug', 'title_ar', 'title_en', 'summary_ar', 'summary_en', 'tag_ar', 'tag_en', 'pages', 'cover_index', 'cover_position', 'sort_order'],
        [[q(d['slug']), q(d['title']['ar']), q(d['title']['en']), q(d['summary']['ar']), q(d['summary']['en']),
          q(d['tag']['ar']), q(d['tag']['en']), arr(d['pages']), str(d['cover']), q(d['cover_position']), str(d['sort'])]
         for d in data['decks']]))
    sql.append(upsert('graphics',
        ['slug', 'category', 'image_path', 'caption_ar', 'caption_en', 'sort_order'],
        [[q(g['slug']), q(g['category']), q(g['image']), q(g['caption']['ar']), q(g['caption']['en']), str(g['sort'])]
         for g in data['graphics']]))
    SQL_OUT.write_text('\n'.join(sql), encoding='utf-8')
    print(f'wrote {JS_OUT.relative_to(ROOT)} and {SQL_OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
